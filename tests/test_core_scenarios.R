raw <- read.csv("data/core/primary_raw.csv", stringsAsFactors = FALSE)
# V4 loaded this table with readxl (numeric N/R); keep the same column types so identical() checks compare values, not storage mode.
raw$N <- as.numeric(raw$N)
raw$R <- as.numeric(raw$R)
spec <- core_scenario_spec()
primary <- build_core_scenario(raw, "primary")

row_value <- function(data, study, treatment) {
  row <- data[data$Study == study & data$T == treatment, c("N", "R"), drop = FALSE]
  stopifnot(nrow(row) == 1L)
  setNames(as.numeric(row[1, ]), c("N", "R"))
}

same_rows <- function(left, right) {
  identical(normalize_arm_rows(left), normalize_arm_rows(right))
}

expected_scenarios <- c(
  "primary",
  "sensitivity_exclude_cevik",
  "sensitivity_include_iachetta_kleibl",
  "sensitivity_include_boisdron_overlap",
  "sensitivity_exclude_onesti",
  "sensitivity_exclude_genotype_informed_carriers",
