# Manifest totals are generated by each scenario, not copied from the primary.
for (name in expected_scenarios) {
  expected <- spec[spec$scenario == name, c("expected_studies", "expected_arms", "expected_n", "expected_r")]
  stopifnot(identical(as.numeric(core_totals(scenarios[[name]])), as.numeric(expected[1, ])))
  validate_core_scenario(scenarios[[name]], name)
}

