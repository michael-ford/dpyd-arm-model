  "sensitivity_compound_lower_function",
  "sensitivity_compound_reciprocal"
)
stopifnot(identical(spec$scenario, expected_scenarios), !anyDuplicated(spec$scenario))

scenarios <- setNames(lapply(expected_scenarios, function(name) {
  build_core_scenario(raw, name)
}), expected_scenarios)

# Locked primary manifest, including the fixed-study node-level reconciliation.
